# Program ini menggunakan fungsi input()

ipk_1013 = float(input("Input IPK Anda = "))

if ipk_1013 > 2.75:
        print("Anda Lulus Sangat Memuaskan dengan IPK " + str(ipk_1013))

else:
    print("Anda Tidak Lulus")

