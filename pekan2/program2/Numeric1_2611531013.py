#create a variable with integer value.
a_1013 = 100
print("The type of variable having value", a_1013, "is",
    type(a_1013))

#create a variable with float value.
b_1013 = 10.2345
print("The type of variable having value", b_1013, "is", 
    type (b_1013))

#create a variable with complex value 
c_1013 = 100 + 3j
print("The type of variable having value", c_1013, "is",
    type(c_1013))